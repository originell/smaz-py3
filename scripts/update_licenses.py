"""Generate shipped dependency notices; use --check to detect stale notices."""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE = ROOT / "THIRD_PARTY_LICENSES.txt"
GENERATED_CODE_CRATES = {"pyo3-macros", "pyo3-macros-backend"}
MIT_LICENSES = {"MIT", "MIT OR Apache-2.0", "Apache-2.0 OR MIT"}


def shipped_packages(metadata):
    """Select normal dependencies across targets and PyO3 binding generators."""
    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    root = metadata["resolve"]["root"]
    runtime = set()
    generated = set()
    pending = [root]
    while pending:
        package_id = pending.pop()
        if package_id in runtime:
            continue
        runtime.add(package_id)
        for dependency in nodes[package_id]["deps"]:
            if not any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                continue
            package = packages[dependency["pkg"]]
            if any("proc-macro" in target["kind"] for target in package["targets"]):
                if package["name"] not in GENERATED_CODE_CRATES:
                    raise ValueError(
                        f"Review generated-code notices for {package['name']} "
                        "before adding it to GENERATED_CODE_CRATES."
                    )
                generated.add(package["id"])
                # Retain PyO3's generated binding attribution without pulling
                # in the parser and token-manipulation tools used on the host.
                generated.update(
                    dep["pkg"]
                    for dep in nodes[package["id"]]["deps"]
                    if packages[dep["pkg"]]["name"] in GENERATED_CODE_CRATES
                )
            else:
                pending.append(package["id"])
    return sorted(
        (packages[key] for key in (runtime | generated) - {root}),
        key=lambda package: (package["name"], package["version"]),
    )


def render_notice(packages):
    """Group identical upstream license files while retaining their notices."""
    groups = {}
    for package in packages:
        if package["license"] not in MIT_LICENSES:
            raise ValueError(
                f"Review license {package['license']!r} for {package['name']} "
                "before updating the notice generator."
            )
        source = Path(package["manifest_path"]).parent
        license_file = source / "LICENSE-MIT"
        if not license_file.is_file():
            license_file = source / "LICENSE"
        text = license_file.read_text(encoding="utf-8").strip() + "\n"
        groups.setdefault(text, []).append(f"{package['name']} {package['version']}")
    parts = [
        "Third-party licenses\n\n"
        "Generated by scripts/update_licenses.py from Cargo.lock.\n"
        "Includes runtime dependencies across target platforms and PyO3's\n"
        "generated bindings. Build tools and their dependencies are omitted.\n"
        "The MIT option is selected for dual MIT/Apache-2.0 licenses.\n"
        "Identical upstream license texts are reproduced once per group.\n"
    ]
    for text, names in groups.items():
        parts.append("\n" + "=" * 72 + "\n")
        parts.append("\n".join(names) + "\n\nMIT license\n\n" + text)
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if notices need regeneration"
    )
    args = parser.parse_args()
    try:
        # No platform filter: one notice file covers all supported wheel targets.
        result = subprocess.run(
            ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        expected = render_notice(shipped_packages(json.loads(result.stdout)))
        if args.check:
            if not NOTICE.is_file() or NOTICE.read_text(encoding="utf-8") != expected:
                print(
                    "Third-party notices are stale. Run "
                    "uv run python scripts/update_licenses.py.",
                    file=sys.stderr,
                )
                return 1
            print("Third-party notices are up to date.")
        else:
            NOTICE.write_text(expected, encoding="utf-8", newline="\n")
            print(f"Updated {NOTICE.name} ({len(expected.encode('utf-8'))} bytes).")
    except subprocess.CalledProcessError as error:
        print(error.stderr, file=sys.stderr)
        print("Run cargo fetch --locked, then retry.", file=sys.stderr)
        return 1
    except (OSError, ValueError) as error:
        print(f"Cannot update third-party notices: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
